import * as monaco from 'monaco-editor/editor/editor.api.js';
import {createSourceEditor} from '../frontend/editor/editor.js';
import {completionContext} from '../frontend/editor/riscv.js';
const source = '.text\n.globl _start\n_start:\n    addi t0, zero, 1\n    add t1, t0, t0\n\nEnd:\n    li a0, 0\n    li a7, 93\n    ecall\n';
let changes = 0;
const adapter = createSourceEditor(document.querySelector('#source-editor'), {onChange:()=>changes++,onSave:()=>{}});
window.harness = {adapter,monaco,source,results:[]};
const check = (condition, message) => { if (!condition) throw Error(message); window.harness.results.push(message); };
window.runEditorTests = async () => {
  adapter.replaceDocument(source,'test.s');
  const editor = monaco.editor.getEditors()[0];
  const model = editor.getModel();
  const edit = (line,start,end,text) => ({range:new monaco.Range(line,start,line,end),text});
  editor.setPosition({lineNumber:4,column:5});
  editor.trigger('test','type',{text:'x'});
  check(adapter.getValue().includes('xaddi'), 'typing changes editable text');
  model.pushStackElement(); await model.undo();
  check(adapter.getValue() === source, 'undo restores source');
  await model.redo();
  check(adapter.getValue().includes('xaddi'), 'redo restores edit');
  await model.undo();
  editor.setPosition({lineNumber:1,column:1});
  editor.trigger('test','type',{text:'x'});
  check(adapter.getValue() === source, 'typing cannot modify protected text');
  editor.executeEdits('test',[edit(4,5,9,'sub'),edit(10,5,10,'nop')]);
  check(adapter.getValue() === source, 'mixed protected and editable transaction is atomic');
  editor.executeEdits('test',[{range:new monaco.Range(6,1,7,1),text:''}]);
  check(adapter.getValue() === source, 'deleting newline before a protected line is rejected');
  editor.executeEdits('test',[{range:model.getFullModelRange(),text:'replaced'}]);
  check(adapter.getValue() === source, 'whole-document replacement is rejected');
  // Exercise the actual find controller, not just its model edit equivalent.
  const find = editor.getContribution('editor.contrib.findController');
  find.getState().change({searchString:'li',replaceString:'nop',isRegex:false,matchCase:false,wholeWord:false},false);
  find.replaceAll();
  check(adapter.getValue() === source, 'find replace-all cannot modify scaffold');
  editor.setSelections([new monaco.Selection(4,5,4,5),new monaco.Selection(5,5,5,5)]);
  editor.trigger('test','type',{text:' '});
  check(adapter.getValue().includes('     addi') && adapter.getValue().includes('     add t1'), 'editable multi-cursor transaction works');
  model.pushStackElement(); await model.undo();
  check(adapter.getValue() === source, 'multi-cursor undo remains usable after rejected edits');
  editor.setSelection(new monaco.Selection(3,1,5,1));
  editor.trigger('test','tab',{});
  check(adapter.getValue() === source, 'indent spanning scaffold is rejected');
  editor.setPosition({lineNumber:4,column:5});
  editor.trigger('test','paste',{text:'mv t2, t0\n    ',pasteOnNewLine:false,multicursorText:null});
  check(adapter.getValue().includes('mv t2, t0'), 'paste into body works');
  model.pushStackElement(); await model.undo();
  check(adapter.getValue() === source,'paste undo works');
  editor.executeEdits('test',[edit(4,5,9,'sub')]);
  model.pushStackElement();
  const count = changes;
  adapter.highlightLine(4,true);
  check(changes === count && model.getAllDecorations().some(d=>d.options.className === 'ase-pipeline-line'), 'pipeline decoration does not edit source');
  const worker = monaco.editor.createWebWorker({moduleId:'vs/editor/editorWorkerService',label:'test'});
  await worker.withSyncedResources([model.uri]);
  worker.dispose();
  check(true,'local editor worker starts and synchronizes source');
  adapter.replaceDocument(source,'reload.s',{preserveView:true});
  check(model.isDisposed() && monaco.editor.getModels().length === 1, 'document replacement disposes previous model');
  await editor.getModel().undo();
  check(adapter.getValue() === source,'replacement resets undo history');
  check(!completionContext('# add'),'completion is suppressed in comments');
  adapter.setFontSize(20); adapter.setTheme(true);
  check(editor.getOption(monaco.editor.EditorOption.fontSize) === 20,'font preference applied');
  check(document.querySelector('.monaco-editor.vs-dark'),'dark theme applied');
  adapter.find();
  check(document.querySelector('.find-widget'),'find widget available');
  adapter.replaceDocument(Array.from({length:10000},(_,i)=>`label${i}: addi t0, t0, 1`).join('\n'),'large.s');
  adapter.highlightLine(9999,true);
  check(editor.getModel().getLineCount() === 10000,'large document loads and reveals source line');
  adapter.replaceDocument('',null);
  check(monaco.editor.getModels().length === 0,'closing project disposes model');
  adapter.replaceDocument(source,'test.s');
  window.harness.done = true;
  return window.harness.results;
};
window.harness.ready = true;
