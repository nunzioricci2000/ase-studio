// Modified in the personal fork on 2026-10-27: seed an interrupted-save draft explicitly.
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const url=process.argv[2];
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium'});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url);
 await page.getByRole('button',{name:'arithmetic',exact:true}).click();
 const diskSource=(await (await page.request.get(url+'/api/project?name=arithmetic')).json()).text;
 await page.evaluate(text=>localStorage.setItem('ase-studio-draft:arithmetic',JSON.stringify({text:'# recovered upstream draft\n'+text,timestamp:Date.now()})),diskSource);
 await page.reload();
 await page.getByRole('button',{name:'arithmetic',exact:true}).click();
 await page.getByRole('button',{name:'Recover',exact:true}).click();
 assert.ok((await page.locator('.view-lines').innerText()).replaceAll('\u00a0', ' ').includes('recovered upstream draft'));
 await page.locator('#save').click();
 await page.waitForFunction(()=>!window.aseHasUnsavedChanges());
 assert.equal(await page.evaluate(()=>localStorage.getItem('ase-studio-draft:arithmetic')),null);
 console.log('PASS Monaco draft autosave, recovery and cleanup after save');
 // Unlock a protected directive, edit it and restore it with Monaco undo.
 await page.locator('#scaffold-protection').uncheck();
 await page.locator('.monaco-editor').first().click();
 const source=(await (await page.request.get(url+'/api/project?name=arithmetic')).json()).text;
 const startLine=source.split('\n').findIndex(line=>line.trim()==='_start:');
 assert.ok(startLine>=0);
 await page.keyboard.press('Control+Home');
 for(let i=0;i<startLine;i++) await page.keyboard.press('ArrowDown');
 await page.keyboard.press('Home');
 await page.keyboard.press('Shift+End');
 await page.keyboard.insertText('_broken_start:');
 await page.waitForFunction(()=>window.aseHasUnsavedChanges());
 assert.ok((await page.locator('.view-lines').innerText()).includes('_broken_start:'));
 await page.keyboard.press('Control+z');
 await page.waitForFunction(()=>!window.aseHasUnsavedChanges());
 await page.locator('#scaffold-protection').check();
 console.log('PASS label protection toggle and undo use Monaco');
 // Compiler diagnostics retain navigation to the Monaco source.
 await page.locator('.monaco-editor').first().click();
 await page.keyboard.press('Control+Home');
 await page.keyboard.insertText('not_an_opcode t0, t1\n');
 const response=page.waitForResponse(r=>r.url().endsWith('/api/run'));
 await page.locator('#run').click();
 assert.equal((await (await response).json()).ok,false);
 await page.locator('#diagnostics .diagnostic-item[data-diagnostic-index]').first().click();
 await page.locator('.ase-pipeline-line').first().waitFor();
 await page.request.post(url+'/api/save',{data:{name:'arithmetic',text:source}});
 await page.reload();
 await page.getByRole('button',{name:'arithmetic',exact:true}).click();
 await page.waitForFunction(()=>!window.aseHasUnsavedChanges());
 console.log('PASS compiler diagnostic navigation into Monaco');
 await page.locator('#configure').click();
 await page.locator('#cpu-model').selectOption('out-of-order');
 assert.equal(await page.locator('#cpu-model').inputValue(),'out-of-order');
 await page.locator('#o3-branch-predictor').selectOption('tournament');
 await page.locator('#o3-predictor-parameters').click();
 await page.locator('#predictor-dialog[open]').waitFor();
 assert.ok(await page.locator('#predictor-fields input').count()>0);
 await page.locator('#cancel-predictor').click();
 await page.locator('#cancel-config').click();
 await page.locator('[data-tab=memory]').click();
 const popupPromise=page.waitForEvent('popup');
 await page.locator('#memory-popout').click();
 const popup=await popupPromise;
 popup.on('pageerror',e=>errors.push(e.message));
 await popup.waitForLoadState();
 assert.ok(popup.url().endsWith('/memory-window.html'));
 await popup.close();
 console.log('PASS predictor parameters and memory pop-out');
 await page.screenshot({path:'/tmp/ase-upstream-integration.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS superscalar configuration opens without JavaScript errors');
} finally {await browser.close();}
