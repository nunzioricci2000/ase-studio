// Usage: node tests/studio-browser.mjs URL SCRATCH_ROOT (from studio-server.py)
import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
const [url,root]=process.argv.slice(2);
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',route=>route.request().url().startsWith(url+'/')?route.continue():route.abort());
  await page.goto(url);
  await page.getByRole('button',{name:'arithmetic',exact:true}).click();
  await page.locator('.view-lines .view-line').first().waitFor();
  await page.locator('.monaco-editor').first().click();
  await page.keyboard.press('Control+Home');
  await page.keyboard.insertText('# Monaco UI test\n');
  await page.waitForFunction(()=>window.aseHasUnsavedChanges());
  await page.keyboard.press('Control+s');
  await page.waitForFunction(()=>!window.aseHasUnsavedChanges());
  const path=`${root}/programs/arithmetic/main.s`;
  assert.ok((await readFile(path,'utf8')).startsWith('# Monaco UI test\n'));
  console.log('PASS full application Ctrl+S saves Monaco text');
  await page.keyboard.press('Control+f');
  await page.locator('.find-widget.visible').waitFor();
  await page.keyboard.press('Escape');
  console.log('PASS full application Ctrl+F opens Monaco search');
  await page.keyboard.press('Control+Home');
  await page.keyboard.insertText('# discard me\n');
  await page.getByRole('button',{name:'loop',exact:true}).click();
  await page.locator('#message-dialog[open]').waitFor();
  // The existing dialog exposes an explicit discard action.
  await page.getByRole('button',{name:'Discard',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#project-title').textContent==='loop');
  await page.getByRole('button',{name:'arithmetic',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#project-title').textContent==='arithmetic');
  assert.ok(!(await page.locator('.view-lines').innerText()).includes('discard me'));
  console.log('PASS project switching prompts and discards edits');
  await writeFile(path, '# external edit\n'+await readFile(path,'utf8'));
  await page.waitForFunction(()=>document.querySelector('.view-lines').textContent.replaceAll('\u00a0',' ').includes('external edit'));
  assert.equal(await page.evaluate(()=>window.aseHasUnsavedChanges()),false);
  console.log('PASS external file reload preserves clean state');
  await page.locator('#theme-toggle').click();
  await page.locator('#editor-font-size').evaluate(el=>{el.value='18';el.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.reload();
  await page.getByRole('button',{name:'arithmetic',exact:true}).click();
  assert.equal(await page.locator('#editor-font-size').inputValue(),'18');
  const dark=await page.locator('html').getAttribute('data-theme')==='dark';
  await page.locator(dark ? '.monaco-editor.vs-dark' : '.monaco-editor.vs').waitFor();
  console.log('PASS theme and font preferences survive reload');
  const response=page.waitForResponse(r=>r.url().endsWith('/api/run'));
  await page.locator('#run').click();
  assert.equal((await (await response).json()).ok,true);
  await page.locator('#pipeline-grid .pipeline-row .cell.inst').first().waitFor();
  await page.locator('#pipeline-grid .pipeline-row .cell.inst').first().click({button:'right'});
  await page.screenshot({path:'/tmp/ase-monaco-studio.png'});
  await page.locator('.ase-pipeline-line').first().waitFor();
  assert.equal(await page.evaluate(()=>window.aseHasUnsavedChanges()),false);
  console.log('PASS real simulator run and pipeline-to-source highlighting');
  await page.setViewportSize({width:1000,height:740});
  await page.screenshot({path:'/tmp/ase-monaco-studio.png'});
  assert.deepEqual(errors,[]);
} finally {await browser.close();}
